import { TABS, TabId } from '../engine/urlState';
import { copyLink, openMission, resetView, setLive, setPreset, setTab, toggleTheme } from '../state/actions';
import { fmtClock, fmtDuration } from '../state/format';
import { MISSION_STEPS } from '../state/mission';
import { setState, useStore } from '../state/store';
import { Icon } from './Icon';
import { useView } from './hooks';

const LABEL: Record<TabId, string> = { overview: 'Overview', logs: 'Logs', alerts: 'Alerts', incidents: 'Incidents' };
const PRESETS = [
  { m: 15, l: '15m' },
  { m: 60, l: '1h' },
  { m: 360, l: '6h' },
  { m: 1440, l: '24h' },
];

export function TopBar() {
  const tab = useStore((s) => s.tab);
  const live = useStore((s) => s.live);
  const spanSec = useStore((s) => s.spanSec);
  const theme = useStore((s) => s.theme);
  const firing = useStore((s) => s.alerts.filter((a) => a.resolvedAt == null).length);
  const incOpen = useStore((s) => s.incidents.filter((i) => i.status !== 'resolved').length);
  const done = useStore((s) => MISSION_STEPS.filter((m) => s.mission.done[m.id]).length);
  const view = useView();
  const badge = (t: TabId) => (t === 'alerts' && firing ? firing : t === 'incidents' && incOpen ? incOpen : 0);
  return (
    <header className="topbar">
      <div className="brand">
        <svg width="22" height="22" viewBox="0 0 32 32" aria-hidden>
          <rect width="32" height="32" rx="7" fill="var(--panel-2)" />
          <path d="M3 17h6l3-9 5 17 4-12 2 4h6" fill="none" stroke="var(--ok)" strokeWidth="2.6" strokeLinecap="round" strokeLinejoin="round" />
        </svg>
        <b>pulse</b>
        <span className="sim-badge" title="Every metric, log and alert in this console is generated by a seeded simulator running in a Web Worker.">
          simulated data
        </span>
      </div>
      <nav className="tabs" aria-label="Sections">
        {TABS.map((t) => (
          <button key={t} className={tab === t ? 'on' : ''} aria-current={tab === t ? 'page' : undefined} onClick={() => setTab(t)}>
            {LABEL[t]}
            {badge(t) > 0 && <span className={`tab-badge ${t}`}>{badge(t)}</span>}
          </button>
        ))}
      </nav>
      <div className="controls">
        <div className="presets" role="group" aria-label="Time range">
          {PRESETS.map((p) => (
            <button key={p.m} className={live && spanSec === p.m * 60 ? 'on' : ''} onClick={() => setPreset(p.m)} aria-pressed={live && spanSec === p.m * 60}>
              {p.l}
            </button>
          ))}
        </div>
        <button className={`live-btn ${live ? 'live' : 'paused'}`} aria-pressed={live} onClick={() => setLive(!live)} title="Toggle live follow (End key on a chart returns to live)">
          <span className={`dot ${live ? 'live' : ''}`} />
          {live ? 'Live' : 'Paused'}
          <Icon name={live ? 'pause' : 'play'} size={11} />
        </button>
        <span className="range" data-testid="range" title="Visible time range, double-click any chart to reset">
          {fmtClock(view.from, false)} to {fmtClock(view.to, false)} UTC <em>({fmtDuration(view.to - view.from)})</em>
        </span>
        <button className="icon-btn" aria-label="Reset time range to live" title="Reset view" onClick={resetView}>
          <Icon name="reset" />
        </button>
      </div>
      <div className="right">
        <button className="btn ghost kbd-btn" onClick={() => setState({ palette: true })} aria-label="Open command palette">
          <Icon name="search" /> <span className="hide-sm">Search</span> <kbd>⌘K</kbd>
        </button>
        <button className="icon-btn" aria-label="Copy link to this view" title="Copy link to this exact view" onClick={copyLink}>
          <Icon name="link" />
        </button>
        <button className="icon-btn" aria-label={`Switch to ${theme === 'dark' ? 'light' : 'dark'} theme`} onClick={toggleTheme}>
          <Icon name={theme === 'dark' ? 'sun' : 'moon'} />
        </button>
        <button className="btn mission-pill" onClick={openMission} aria-label={`Open mission, ${done} of ${MISSION_STEPS.length} steps done`}>
          <Icon name="flag" /> Mission {done}/{MISSION_STEPS.length}
        </button>
      </div>
    </header>
  );
}
